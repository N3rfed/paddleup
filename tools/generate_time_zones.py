"""Generate the server-only IANA transition subset. Python 3.9+, no installed tzdata needed.
Reads verified public TZif data, never executes wheel code. Run from the repository root.
"""
from datetime import datetime, timezone
from zoneinfo import ZoneInfo
from pathlib import Path
from urllib.request import urlopen
from io import BytesIO
from zipfile import ZipFile
import hashlib
import struct

URL = "https://files.pythonhosted.org/packages/94/21/1e5995a1c920cce14e4bffae20c665ec10e7ed03ab25e006cd741092b718/tzdata-2026.5-py2.py3-none-any.whl"
SHA256 = "b683bd1b6659ddcd810ff02ad09ba821d4bf1065072805063eb35c49617905ac"
START = int(datetime(2020, 1, 1, tzinfo=timezone.utc).timestamp())
END = int(datetime(2041, 1, 1, tzinfo=timezone.utc).timestamp())

def generate():
    raw = urlopen(URL, timeout=45).read()
    assert hashlib.sha256(raw).hexdigest() == SHA256, "tzdata archive checksum mismatch"
    archive = ZipFile(BytesIO(raw))
    # All IANA zone.tab locations, plus UTC. No hand-maintained geographic allowlist.
    zones = {"UTC"}
    for line in archive.read("tzdata/zoneinfo/zone.tab").decode().splitlines():
        if line and not line.startswith("#"): zones.add(line.split("\t")[2])
    result = ["-- Generated by tools/generate_time_zones.py; IANA 2026e / python-tzdata 2026.5.",
        "-- Public-domain IANA data. Do not edit transitions by hand; refresh when IANA rules change.",
        "return {version=\"2026e\",start=" + str(START) + ",finish=" + str(END) + ",zones={"]
    total = 0
    for name in sorted(zones):
        blob = archive.read("tzdata/zoneinfo/" + name)
        zone = ZoneInfo.from_file(BytesIO(blob))
        counts = struct.unpack(">6I", blob[20:44])
        header, width = 0, 4
        if blob[4:5] != b"\x00":
            gmt, std, leap, times, types, chars = counts
            header = 44 + times * 5 + types * 6 + chars + leap * 8 + std + gmt
            counts = struct.unpack(">6I", blob[header+20:header+44])
            width = 8
        count = counts[3]
        explicit = struct.unpack(">" + ("q" if width == 8 else "l") * count, blob[header+44:header+44+count*width])
        def offset(at):
            return int(datetime.fromtimestamp(at, timezone.utc).astimezone(zone).utcoffset().total_seconds())
        previous = offset(START)
        pairs = [(START, previous)]
        at = START
        # Scan six-hour intervals and locate every change to exact Unix-second precision.
        while at < END - 1:
            high = min(at + 21600, END - 1)
            current = offset(high)
            if current != previous:
                low = at
                while high - low > 1:
                    middle = (low + high) // 2
                    if offset(middle) == previous: low = middle
                    else: high = middle
                previous = offset(high)
                pairs.append((high, previous))
            at = min(at + 21600, END - 1)
        found = {t for t, _ in pairs}
        expected = {t for t in explicit if START < t < END and offset(t-1) != offset(t)}
        assert expected <= found, f"Missed an explicit IANA transition in {name}"
        total += len(pairs)
        result.append(" [\"" + name + "\"]={" + ",".join("{" + str(t) + "," + str(o) + "}" for t, o in pairs) + "},")
    result.append("}}")
    Path("src/server/TimeZoneData.luau").write_text("\n".join(result) + "\n", encoding="utf-8")
    print(f"Generated {len(zones)} zones, {total} offset segments from IANA 2026e; SHA-256 verified.")

if __name__ == "__main__":
    generate()
